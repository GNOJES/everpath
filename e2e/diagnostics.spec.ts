import { readFileSync } from 'node:fs';
import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('mobile diagnostics records raw frames and touch timing, exports JSON and retains opt-in', async ({ browser }) => {
 const context = await browser.newContext({ viewport: { width: 360, height: 640 }, isMobile: true, hasTouch: true });
 const page = await context.newPage(), errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
 await page.goto('/'); await expect(page.locator('#diagnostics-hud')).toBeHidden();
 await page.getByRole('button', { name: '설정', exact: true }).click();
 await page.locator('#overlay [data-action="diagnostics"]').click();
 await page.locator('[data-action="diagnostics-toggle"]').click();
 await expect(page.locator('[data-action="diagnostics-toggle"]')).toHaveAttribute('aria-pressed', 'true');
 await page.locator('#diagnostics-note').fill('궁수 · <script>메모</script> · 60Hz');
 await page.locator('[data-action="diagnostics-back"]').last().click();
 await page.locator('[data-action="settings-back"]').last().click();
 await page.locator('[data-action="embark"]').click(); await page.locator('[data-hero="archer"]').click(); await page.locator('[data-action="start"]').click();
 await expect(page.locator('#diagnostics-hud')).toBeVisible();
 await expect.poll(async () => Number(await page.locator('#diagnostics-hud [data-diag-fps]').textContent())).toBeGreaterThan(0);
 const touch = await context.newCDPSession(page), rect = (await page.locator('canvas').boundingBox())!;
 const x = rect.x + rect.width * .5, y = rect.y + rect.height * .7;
 await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y, id: 1 }] });
 await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x + 30, y, id: 1 }] });
 await expect(page.locator('#diagnostics-hud [data-diag-touch]')).toContainText('DRAG');
 await page.waitForTimeout(1200);
 await touch.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] });
 await expect(page.locator('#diagnostics-hud [data-diag-touch]')).toContainText('IDLE');
 await page.getByRole('button', { name: '진단 로그 열기' }).click();
 await expect(page.getByRole('heading', { name: '실기기 진단', exact: true })).toBeVisible();
 await page.keyboard.down('w'); await page.waitForTimeout(1300); await page.keyboard.up('w');
 await page.locator('[data-action="diagnostics-back"]').last().click(); await page.locator('[data-action="resume"]').click();
 await page.waitForTimeout(1100); await page.getByRole('button', { name: '진단 로그 열기' }).click();
 const downloadPromise = page.waitForEvent('download'); await page.locator('[data-action="diagnostics-export"]').click();
 const download = await downloadPromise; expect(download.suggestedFilename()).toMatch(/^everpath-diagnostics-.*\.json$/);
 const report = JSON.parse(await readFile((await download.path())!, 'utf8'));
 expect(report.appVersion).toBe(JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8')).version); expect(report.environment.platform).toBe('web');
 expect(report.note).toBe('궁수 · <script>메모</script> · 60Hz'); expect(report.summary.running.frames).toBeGreaterThan(0);
 expect(report.samples.some((sample: any) => sample.inputLatency.count > 0 && sample.inputLatency.maxMs >= 0)).toBe(true);
 expect(report.events.some((event: any) => event.kind === 'input' && event.data.action === 'cancel')).toBe(true);
 expect(Math.max(...report.samples.map((sample: any) => sample.inputLatency.maxMs))).toBeLessThan(1000);
 expect(report.retention.sampleLimit).toBe(1800); expect(report.retention.eventLimit).toBe(4000);
 await page.screenshot({ path: 'test-results/diagnostics-mobile.png' });
 await page.locator('[data-action="diagnostics-toggle"]').click();
 const stoppedPromise = page.waitForEvent('download'); await page.locator('[data-action="diagnostics-export"]').click();
 const stopped = JSON.parse(await readFile((await (await stoppedPromise).path())!, 'utf8'));
 expect(stopped.active).toBe(false); expect(stopped.summary.running.frames).toBe(report.summary.running.frames);
 await page.locator('[data-action="diagnostics-new"]').click();
 await expect(page.locator('[data-diag-counts]')).toContainText('측정 프레임 0');
 await page.locator('[data-action="diagnostics-toggle"]').click(); await page.reload();
 await page.getByRole('button', { name: '설정', exact: true }).click(); await page.locator('#overlay [data-action="diagnostics"]').click();
 await expect(page.locator('[data-action="diagnostics-toggle"]')).toHaveAttribute('aria-pressed', 'true');
 expect(errors).toEqual([]); await context.close();
});

